/* ==========================================================================
 * help.js —— 使用帮助模块
 * 提供内置帮助文档的 HTML 内容与显示/隐藏逻辑。
 * 挂载到全局命名空间 window.PokerHelp，供 actions.js / app.js 调用。
 * ========================================================================== */
(function () {
  "use strict";

  /** 帮助文档 HTML 内容（静态常量，纯展示） */
  var HELP_HTML =
    "<h4>快速开始</h4>" +
    "<ul>" +
    "<li>输入昵称，点击『进入牌桌』加入游戏；<b>首位加入者自动成为房主</b>。</li>" +
    "<li>房主点击『开始游戏』发牌；每局结束后可再次点击开始下一局。</li>" +
    "<li>轮到自己行动时，行动区按钮会高亮：弃牌 / 让牌 / 跟注 / 加注 / 全下。</li>" +
    "</ul>" +
    "<h4>行动说明</h4>" +
    "<ul>" +
    "<li><b>弃牌</b>：放弃本局，不再参与底池争夺。</li>" +
    "<li><b>让牌</b>：不加注、不弃牌，仅当无人需要你补注时可用。</li>" +
    "<li><b>跟注</b>：补足与当前最高注相同的筹码。</li>" +
    "<li><b>加注</b>：把总下注提高到输入金额，须在最小与最大区间内。</li>" +
    "<li><b>全下</b>：押上全部剩余筹码。</li>" +
    "</ul>" +
    "<h4>房间操作</h4>" +
    "<ul>" +
    "<li><b>重置房间</b>（仅房主）：清零对局数、恢复所有玩家筹码，保留玩家列表与规则；<br>执行前会弹出确认框防止误操作。</li>" +
    "<li><b>玩家列表</b>：查看当前所有玩家及其筹码。</li>" +
    "</ul>" +
    "<h4>服务器控制台（管理员）</h4>" +
    "<ul>" +
    "<li>顶栏的 <b>启动 / 暂停 / 恢复 / 停止</b> 按钮用于控制游戏服务器进程。</li>" +
    "<li>暂停期间所有行动请求会被拒绝（牌局冻结不丢状态），恢复后继续。</li>" +
    "<li>停止会断开所有在线玩家并关闭服务器，请谨慎操作。</li>" +
    "</ul>" +
    "<h4>常见问题</h4>" +
    "<ul>" +
    "<li>连接中断：页面会自动重连并接管原席位（最多 3 次尝试）。</li>" +
    "<li>行动被拒绝：请检查是否轮到你、是否有足够筹码、服务器是否暂停。</li>" +
    "<li>刷新页面会退出当前会话，需重新输入昵称加入。</li>" +
    "</ul>";

  /** 在指定容器内切换帮助面板的显示/隐藏 */
  function toggleHelp(container) {
    if (!container) return;
    if (container.classList.contains("hidden")) {
      // 首次展开时写入内容（HTML 注入是静态常量，无用户输入风险）
      if (!container.innerHTML) {
        container.innerHTML = HELP_HTML;
      }
      container.classList.remove("hidden");
    } else {
      container.classList.add("hidden");
    }
  }

  // 暴露全局接口（避免与其他模块命名冲突）
  window.PokerHelp = {
    toggleHelp: toggleHelp,
    getHtml: function () {
      return HELP_HTML;
    }
  };
})();
